"""Use-case-driven repository contracts, grouped by business ownership."""
from contextlib import AbstractContextManager
from typing import Protocol

from .modules.context import Delivery
from .modules.findings import Finding, Issue
from .modules.governance import TestReport
from .modules.knowledge import ContractProposal, Rule
from .modules.tasks import Requirement, Task
from .modules.workspaces import Worktree
from .modules.topics import Topic


class TopicsPort(Protocol):
    def state(self, project_id: str) -> dict: ...
    def get(self, project_id: str, key: str) -> Topic | None: ...
    def list(self, project_id: str, query: str = '', include_deleted: bool = False,
             cursor: str | None = None, limit: int = 50) -> list[Topic]: ...
    def create(self, topic: Topic) -> None: ...
    def update(self, topic: Topic, expected_version: int) -> None: ...
    def lock(self, project_id: str, keys: tuple[str, ...]) -> None: ...
    def usage(self, project_id: str, key: str) -> dict: ...
    def coverage(self, project_id: str) -> dict: ...
    def enable(self, project_id: str, expected_revision: int) -> None: ...


class WorkspacesPort(Protocol):
    def project_revision(self, project_id: str) -> int: ...
    def create_project(self, project_id: str, name: str) -> None: ...
    def delete_project(self, project_id: str) -> None: ...
    def list_projects(self) -> list[dict]: ...
    def counts(self, project_id: str) -> dict: ...
    def get_task(self, task_id: str, project_id: str | None = None) -> Task | None: ...
    def list_tasks(self, project_id: str, *, requirement_id: str | None = None,
                   statuses: tuple[str, ...] | None = None, cursor: str | None = None,
                   limit: int | None = None) -> list[Task]: ...
    def create_task(self, task: Task) -> None: ...
    def update_task(self, task: Task, expected_version: int) -> None: ...
    def task_context_revision(self, task_id: str) -> int: ...
    def task_versions(self, task_id: str, cursor: int | None = None, limit: int = 20) -> list[dict]: ...
    def request(self, project_id: str, operation: str, request_id: str | None) -> tuple[str, dict] | None: ...
    def record_request(self, project_id: str, operation: str, request_id: str | None,
                       fingerprint: str, result: dict) -> None: ...
    def register_worktree(self, worktree: Worktree) -> None: ...
    def project_worktrees(self, project_id: str) -> list[Worktree]: ...


class RequirementsPort(Protocol):
    def get_requirement(self, requirement_id: str, project_id: str | None = None) -> Requirement | None: ...
    def create_requirement(self, item: Requirement) -> None: ...
    def project_requirements(self, project_id: str, *, statuses: tuple[str, ...] | None = None,
                             cursor: str | None = None, limit: int | None = None) -> list[Requirement]: ...
    def versions(self, requirement_id: str, cursor: int | None = None, limit: int = 20) -> list[dict]: ...
    def update_requirement(self, item: Requirement, expected_version: int) -> None: ...
    def progress(self, requirement_ids: list[str]) -> dict: ...


class KnowledgePort(Protocol):
    def project_rules(self, project_id: str) -> list[dict]: ...
    def create_rule(self, rule: Rule, origin: tuple[str, int] | None = None) -> None: ...
    def get_rule(self, rule_id: str) -> Rule | None: ...
    def rule_snapshot(self, rule_id: str, version: int) -> dict | None: ...
    def promoted_rule(self, source_id: str, source_version: int) -> Rule | None: ...
    def deprecate_rule(self, rule: Rule) -> None: ...
    def update_rule(self, rule: Rule) -> None: ...
    def deprecate_task_rules(self, task_id: str) -> None: ...
    def visible_rules(self, project_id: str, task_id: str | None) -> list[Rule]: ...
    def create_proposal(self, proposal: ContractProposal) -> None: ...
    def get_proposal(self, proposal_id: str) -> ContractProposal | None: ...
    def list_proposals(self, project_id: str) -> list[ContractProposal]: ...
    def decide_proposal(self, proposal: ContractProposal, status: str,
                        reason: str, reviewer_id: str) -> None: ...


class ContextPort(Protocol):
    def record_finding(self, finding: Finding) -> None: ...
    def pending_findings(self, project_id: str, task_id: str) -> list[Finding]: ...
    def project_findings(self, project_id: str) -> list[Finding]: ...
    def get_finding(self, finding_id: str) -> Finding | None: ...
    def update_finding(self, finding: Finding) -> None: ...
    def get_delivery(self, delivery_id: str) -> dict | None: ...
    def delivery_scope(self, delivery_id: str) -> dict | None: ...
    def save_delivery(self, project_id: str, task_id: str | None, result: Delivery, source: dict) -> None: ...


class FeedbackPort(Protocol):
    def current_rule_scores(self, project_id: str) -> dict[str, dict]: ...
    def record_issue(self, issue: Issue) -> None: ...
    def conflict_issues(self, project_id: str, task_id: str | None) -> list[dict]: ...
    def delivered_rule(self, delivery_id: str, rule_id: str) -> int | None: ...
    def prior_feedback(self, delivery_id: str, rule_id: str) -> tuple[int, str] | None: ...
    def record_feedback(self, delivery_id: str, rule_id: str,
                        version: int, score: int, reason: str) -> None: ...


class GovernancePort(Protocol):
    def state(self, rule_id: str) -> dict | None: ...
    def create_state(self, rule_id: str, version: int, half_life_days: int) -> None: ...
    def reset_state(self, rule_id: str, version: int) -> None: ...
    def test_by_fingerprint(self, task_id: str, fingerprint: str) -> TestReport | None: ...
    def test_report(self, report_id: str) -> TestReport | None: ...
    def record_test(self, report: TestReport, fingerprint: str) -> None: ...
    def observations(self, rule_id: str, evidence_version: int) -> list[tuple[bool, int, str]]: ...
    def observation(self, rule_id: str, evidence_version: int, report_id: str) -> tuple | None: ...
    def check_observations(self, rule_id: str, evidence_version: int, check_id: str) -> list[tuple[bool, int, str]]: ...
    def record_observation(self, rule_id: str, evidence_version: int,
                           report_id: str, supports: bool, reason: str, check_ids: tuple[str, ...]) -> None: ...
    def record_review(self, review_id: str, project_id: str, rule_id: str, rule_version: int,
                      approve: bool, reason: str, reviewer_id: str) -> None: ...


class AuditPort(Protocol):
    def project_audit(self, project_id: str, limit: int = 100,
                      before: int | None = None) -> list[dict]: ...
    def record(self, project_id: str, actor_id: str,
               action: str, entity_id: str, details: dict) -> None: ...


class Transaction(Protocol):
    topics: TopicsPort
    workspaces: WorkspacesPort
    requirements: RequirementsPort
    knowledge: KnowledgePort
    context: ContextPort
    feedback: FeedbackPort
    governance: GovernancePort
    audit: AuditPort


class UnitOfWork(Protocol):
    def read(self) -> AbstractContextManager[Transaction]: ...
    def write(self) -> AbstractContextManager[Transaction]: ...
